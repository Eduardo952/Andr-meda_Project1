/** Mesmo formato de ObservatoryData (lib/observatory-data.ts), sem depender de zod. */
export interface ObservatoryLike {
  date: string;
  apod: N8nApod | null;
  photo: N8nPhoto | null;
  source: "live" | "snapshot" | "unavailable";
  photoSource?: "live" | "snapshot" | "unavailable";
  sample: boolean;
}

/**
 * Combina a resposta do n8n com o fallback (NASA direta ou snapshot local).
 * Cada peça vem do n8n quando existe; só o que faltar usa o fallback, com a proveniência
 * (`source`/`photoSource`) dizendo a verdade sobre de onde cada imagem veio.
 */
export function mergeN8nSol(live: N8nSol, base: ObservatoryLike | null): ObservatoryLike {
  return {
    date: live.earth_date,
    apod: live.apod ?? base?.apod ?? null,
    photo: live.photo ?? base?.photo ?? null,
    source: live.apod ? "live" : (base?.source ?? "unavailable"),
    photoSource: live.photo ? "live" : (base?.photoSource ?? "unavailable"),
    sample: live.apod && live.photo ? false : (base?.sample ?? false),
  };
}
