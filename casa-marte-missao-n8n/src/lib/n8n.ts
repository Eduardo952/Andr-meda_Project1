/**
 * Integração com o n8n (SOMENTE no servidor).
 *
 * O workflow (n8n/mars-bubble-groq-nasa_workflow.json) expõe dois webhooks:
 *   POST {base}/bubble-narrator   -> texto do Bubble (Groq)
 *   GET  {base}/nasa-sol?sol=N&mission=<id> -> fatos NASA + APOD + foto do Sol N
 *
 * Este arquivo é a única fonte de verdade para: resolver as URLs, montar os cabeçalhos,
 * validar a resposta do n8n e cachear. Não importa zod nem módulos do jogo, para poder ser
 * testado isoladamente. Nunca importe este arquivo a partir de código de navegador: os
 * segredos só são lidos dentro de server functions (lib/*.functions.ts).
 */

type Env = Record<string, string | undefined>;

export interface N8nConfig {
  narratorUrl: string | null;
  nasaUrl: string | null;
  secret: string | null;
}

const NARRATOR_PATH = "bubble-narrator";
const NASA_PATH = "nasa-sol";

/** O workflow faz até 7 chamadas HTTP em série (6 s cada), então o GET tem folga própria. */
export const N8N_NASA_TIMEOUT_MS = 45_000;
export const N8N_NARRATOR_TIMEOUT_MS = 6_000;
const SUCCESS_TTL_MS = 24 * 60 * 60 * 1000;
const FAILURE_COOLDOWN_MS = 60 * 1000;

function clean(value: string | undefined): string | null {
  const trimmed = value?.trim();
  return trimmed ? trimmed : null;
}

function validHttpUrl(value: string | null): string | null {
  if (!value) return null;
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:" ? value.replace(/\/+$/, "") : null;
  } catch {
    return null;
  }
}

/**
 * Variáveis (todas opcionais; sem nada configurado o jogo roda 100% offline):
 *   N8N_BASE_URL        prefixo dos webhooks, ex.: https://meu-n8n.com/webhook
 *   N8N_WEBHOOK_URL     URL completa do narrador (compatível com a configuração antiga)
 *   N8N_NASA_URL        URL completa do GET de NASA por Sol
 *   N8N_WEBHOOK_SECRET  enviado como header x-api-key nas duas chamadas
 */
export function resolveN8n(env: Env): N8nConfig {
  const base = validHttpUrl(clean(env["N8N_BASE_URL"]));
  const narratorExplicit = validHttpUrl(clean(env["N8N_WEBHOOK_URL"]));
  const nasaExplicit = validHttpUrl(clean(env["N8N_NASA_URL"]));

  const narratorUrl = narratorExplicit ?? (base ? `${base}/${NARRATOR_PATH}` : null);
  let nasaUrl = nasaExplicit ?? (base ? `${base}/${NASA_PATH}` : null);
  // Configuração antiga: só a URL do narrador. Deriva a de NASA se o caminho for o padrão.
  if (!nasaUrl && narratorExplicit?.endsWith(`/${NARRATOR_PATH}`)) {
    nasaUrl = `${narratorExplicit.slice(0, -NARRATOR_PATH.length)}${NASA_PATH}`;
  }
  return { narratorUrl, nasaUrl, secret: clean(env["N8N_WEBHOOK_SECRET"]) };
}

export function n8nHeaders(secret: string | null, json = false): Record<string, string> {
  return {
    Accept: "application/json",
    ...(json ? { "Content-Type": "application/json" } : {}),
    ...(secret ? { "x-api-key": secret } : {}),
  };
}

/** Mission id: random per game, generated by the game, never a date. Same format the workflow accepts. */
export const MISSION_ID_RE = /^[A-Za-z0-9_-]{8,64}$/;
export function cleanMission(value: unknown): string | null {
  return typeof value === "string" && MISSION_ID_RE.test(value) ? value : null;
}

export function nasaRequestUrl(nasaUrl: string, sol: number, mission?: string | null): string {
  const url = new URL(nasaUrl);
  url.searchParams.set("sol", String(sol));
  const m = cleanMission(mission);
  if (m) url.searchParams.set("mission", m); // the workflow picks the real dates from this id; the game never sends dates
  return url.toString();
}

// ---------- Resposta do GET /nasa-sol ----------

export interface N8nFacts {
  flare: { class: string; magnitude: number; source: "DONKI/FLR" } | null;
  cme: { speed_kms: number; source: "DONKI/CMEAnalysis" } | null;
  mars_impact: {
    level: "none" | "minor" | "glancing_blow" | "direct";
    source: "DONKI/WSAEnlilSimulations";
  } | null;
  weather: {
    temp_avg_c: number; source: "InSight/AT" | "Curiosity/REMS";
    temp_min_c?: number | undefined; temp_max_c?: number | undefined; pressure_pa?: number | undefined; opacity?: string | undefined;
  } | null;
  wind: { speed_avg_ms: number; source: "InSight/HWS" } | null;
  severity: "calm" | "attention" | "alert";
}
export interface N8nApod {
  date: string;
  title: string;
  explanation: string;
  media_type: "image" | "video";
  url: string;
  thumbnail_url?: string | undefined;
  copyright?: string | undefined;
}
export interface N8nPhoto {
  id: string;
  title: string;
  description: string;
  credit: string;
  url: string;
}
/** Game-rule effects derived by the workflow from real data (rules_version "effects-v2"). Not NASA engineering. */
export interface N8nEffects {
  radiation_alert: boolean;
  comm_disruption: "none" | "medium" | "high";
  shield_load_factor: number;
  heating_factor: number;
  panel_factor: number;
  dust_storm_risk: "low" | "medium" | "high" | "unknown";
  mars_season_ls: number | null;
  dust_season: boolean;
}
export interface N8nMissionWindow { earth_dates: string[]; curiosity_sols: number[]; reason: string }
export interface N8nDataDates { curiosity_sol: number | null; apod: string | null; weather: string | null; note: string | null }
export interface N8nSol {
  sol: number;
  earth_date: string;
  insight_sol: string | null;
  /** Fields below exist only with the mission-aware workflow (v3); null with the old one. */
  mission: string | null;
  mission_window: N8nMissionWindow | null;
  data_dates: N8nDataDates | null;
  effects: N8nEffects | null;
  facts: N8nFacts;
  apod: N8nApod | null;
  photo: N8nPhoto | null;
}

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);
const num = (v: unknown): number | null => (typeof v === "number" && Number.isFinite(v) ? v : null);
const str = (v: unknown, max: number): string | null =>
  typeof v === "string" && v.trim() ? v.slice(0, max) : null;
const https = (v: unknown): string | null =>
  typeof v === "string" && v.startsWith("https://") && v.length <= 2048 ? v : null;

function parseFacts(raw: unknown): N8nFacts | null {
  if (!isObj(raw)) return null;
  const f = isObj(raw["flare"]) ? raw["flare"] : null;
  const c = isObj(raw["cme"]) ? raw["cme"] : null;
  const m = isObj(raw["mars_impact"]) ? raw["mars_impact"] : null;
  const w = isObj(raw["weather"]) ? raw["weather"] : null;
  const wd = isObj(raw["wind"]) ? raw["wind"] : null;
  const letter = f && typeof f["class"] === "string" && /^[ABCMX]$/.test(f["class"]) ? f["class"] : null;
  const magnitude = f ? num(f["magnitude"]) : null;
  const speed = c ? num(c["speed_kms"]) : null;
  const level = m && ["none", "minor", "glancing_blow", "direct"].includes(String(m["level"])) ? (m["level"] as "none" | "minor" | "glancing_blow" | "direct") : null;
  const temp = w ? num(w["temp_avg_c"]) : null;
  const wind = wd ? num(wd["speed_avg_ms"]) : null;
  const severity = ["calm", "attention", "alert"].includes(String(raw["severity"])) ? (raw["severity"] as N8nFacts["severity"]) : "calm";
  // Cada fato inválido vira null (= "não aconteceu"), nunca derruba a resposta inteira.
  return {
    flare: letter && magnitude !== null ? { class: letter, magnitude, source: "DONKI/FLR" } : null,
    cme: speed !== null && speed > 0 ? { speed_kms: speed, source: "DONKI/CMEAnalysis" } : null,
    mars_impact: level ? { level, source: "DONKI/WSAEnlilSimulations" } : null,
    weather: temp !== null ? parseWeather(w, temp) : null,
    wind: wind !== null ? { speed_avg_ms: wind, source: "InSight/HWS" } : null,
    severity,
  };
}

function parseWeather(w: Obj | null, temp: number): NonNullable<N8nFacts["weather"]> {
  const source = w && w["source"] === "Curiosity/REMS" ? "Curiosity/REMS" : "InSight/AT";
  const min = w ? num(w["temp_min_c"]) : null, max = w ? num(w["temp_max_c"]) : null, pa = w ? num(w["pressure_pa"]) : null, opacity = w ? str(w["opacity"], 40) : null;
  return {
    temp_avg_c: temp, source,
    ...(min !== null ? { temp_min_c: min } : {}), ...(max !== null ? { temp_max_c: max } : {}),
    ...(pa !== null ? { pressure_pa: pa } : {}), ...(opacity ? { opacity } : {}),
  };
}

function parseEffects(raw: unknown): N8nEffects | null {
  if (!isObj(raw)) return null;
  const risk = ["low", "medium", "high", "unknown"].includes(String(raw["dust_storm_risk"])) ? (raw["dust_storm_risk"] as N8nEffects["dust_storm_risk"]) : "unknown";
  const comm = ["none", "medium", "high"].includes(String(raw["comm_disruption"])) ? (raw["comm_disruption"] as N8nEffects["comm_disruption"]) : "none";
  const factor = (v: unknown) => { const n = num(v); return n !== null && n >= 0 && n <= 3 ? n : 1; };
  return {
    radiation_alert: raw["radiation_alert"] === true, comm_disruption: comm,
    shield_load_factor: factor(raw["shield_load_factor"]), heating_factor: factor(raw["heating_factor"]), panel_factor: factor(raw["panel_factor"]),
    dust_storm_risk: risk, mars_season_ls: num(raw["mars_season_ls"]), dust_season: raw["dust_season"] === true,
  };
}

function parseWindow(raw: unknown): N8nMissionWindow | null {
  if (!isObj(raw) || !Array.isArray(raw["earth_dates"]) || !Array.isArray(raw["curiosity_sols"])) return null;
  const dates = raw["earth_dates"].filter((d): d is string => typeof d === "string" && /^\d{4}-\d{2}-\d{2}$/.test(d)).slice(0, 10);
  const sols = raw["curiosity_sols"].filter((n): n is number => typeof n === "number" && Number.isFinite(n)).slice(0, 10);
  return dates.length ? { earth_dates: dates, curiosity_sols: sols, reason: str(raw["reason"], 40) ?? "unknown" } : null;
}

function parseDataDates(raw: unknown): N8nDataDates | null {
  if (!isObj(raw)) return null;
  return { curiosity_sol: num(raw["curiosity_sol"]), apod: str(raw["apod"], 10), weather: str(raw["weather"], 60), note: str(raw["note"], 400) };
}

function parseApod(raw: unknown): N8nApod | null {
  if (!isObj(raw)) return null;
  const url = https(raw["url"]), title = str(raw["title"], 200), date = str(raw["date"], 10);
  if (!url || !title || !date) return null;
  const copyright = str(raw["copyright"], 200);
  return {
    date, title, url,
    explanation: str(raw["explanation"], 1200) ?? "",
    media_type: raw["media_type"] === "video" ? "video" : "image",
    ...(copyright ? { copyright } : {}),
  };
}

function parsePhoto(raw: unknown): N8nPhoto | null {
  if (!isObj(raw)) return null;
  const url = https(raw["url"]), id = str(raw["id"], 100), title = str(raw["title"], 300);
  if (!url || !id || !title) return null;
  return { id, title, url, description: str(raw["description"], 600) ?? "", credit: str(raw["credit"], 200) ?? "NASA" };
}

/** Valida a resposta do n8n. Retorna null se for de outro Sol ou estiver malformada. */
export function parseN8nSol(raw: unknown, expectedSol: number): N8nSol | null {
  if (!isObj(raw) || raw["sol"] !== expectedSol) return null;
  const earth = typeof raw["earth_date"] === "string" && /^\d{4}-\d{2}-\d{2}$/.test(raw["earth_date"]) ? raw["earth_date"] : null;
  const facts = parseFacts(raw["facts"]);
  if (!earth || !facts) return null;
  return {
    sol: expectedSol, earth_date: earth,
    insight_sol: str(raw["insight_sol"], 20),
    mission: cleanMission(raw["mission"]), mission_window: parseWindow(raw["mission_window"]),
    data_dates: parseDataDates(raw["data_dates"]), effects: parseEffects(raw["effects"]),
    facts, apod: parseApod(raw["apod"]), photo: parsePhoto(raw["photo"]),
  };
}

export interface N8nSolOptions { mission?: string | null | undefined; fetcher?: typeof fetch | undefined; timeoutMs?: number | undefined; now?: number | undefined }

export async function fetchN8nSol(cfg: N8nConfig, sol: number, opts: N8nSolOptions = {}): Promise<N8nSol | null> {
  if (!cfg.nasaUrl) return null;
  const fetcher = opts.fetcher ?? fetch;
  try {
    const res = await fetcher(nasaRequestUrl(cfg.nasaUrl, sol, opts.mission), {
      method: "GET",
      headers: n8nHeaders(cfg.secret),
      signal: AbortSignal.timeout(opts.timeoutMs ?? N8N_NASA_TIMEOUT_MS),
    });
    if (!res.ok) {
      console.error(`n8n nasa-sol failed [${res.status}]`);
      return null;
    }
    return parseN8nSol(await res.json(), sol);
  } catch (e) {
    console.error("n8n nasa-sol error", e instanceof Error ? e.message : e);
    return null;
  }
}

const MAX_CACHED_MISSIONS = 500;

/**
 * Cache por MISSAO + Sol (antes era so por Sol e valia para todos os jogadores): guarda so sucessos (24 h),
 * deduplica chamadas simultaneas e, depois de uma falha, nao tenta de novo por 60 s -- assim um n8n fora do ar
 * nao prende cada tela por 45 s. Missoes diferentes nunca compartilham dados.
 */
export class N8nSolCache {
  private ok = new Map<string, { at: number; value: N8nSol }>();
  private failedAt = new Map<string, number>();
  private pending = new Map<string, Promise<N8nSol | null>>();

  async get(cfg: N8nConfig, sol: number, opts: N8nSolOptions = {}): Promise<N8nSol | null> {
    if (!cfg.nasaUrl) return null;
    const now = opts.now ?? Date.now();
    const key = `${cleanMission(opts.mission) ?? "-"}|${sol}`;
    const hit = this.ok.get(key);
    if (hit && now - hit.at < SUCCESS_TTL_MS) return hit.value;
    const failed = this.failedAt.get(key);
    if (failed !== undefined && now - failed < FAILURE_COOLDOWN_MS) return null;
    const active = this.pending.get(key);
    if (active) return active;
    const request = fetchN8nSol(cfg, sol, opts)
      .then((value) => {
        if (value) {
          this.ok.set(key, { at: now, value }); this.failedAt.delete(key);
          if (this.ok.size > MAX_CACHED_MISSIONS * 5) { const oldest = this.ok.keys().next().value; if (oldest !== undefined) this.ok.delete(oldest); }
        } else {
          this.failedAt.set(key, now);
          if (this.failedAt.size > MAX_CACHED_MISSIONS * 5) { const oldest = this.failedAt.keys().next().value; if (oldest !== undefined) this.failedAt.delete(oldest); }
        }
        return value;
      })
      .finally(() => this.pending.delete(key));
    this.pending.set(key, request);
    return request;
  }
}

export const n8nSolCache = new N8nSolCache();

