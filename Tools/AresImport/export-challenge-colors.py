"""Export the reference UI's OKLCH roles to sRGB for UI Toolkit and Painter2D.

Only reads the reference; run from the repository root. Keep color choices in
the reference stylesheet, not in independently maintained C#/USS palettes.
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'a896f420-3053-49eb-b6f2-a97f9b2dc6c8 (4)/src/styles.css'
text = SOURCE.read_text(encoding='utf-8')
tokens = {name: tuple(map(float, values.split())) for name, values in
          re.findall(r'--([\w-]+):\s*oklch\(([^)]+)\)', text)}


def rgb(value):
    light, chroma, hue = value
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l = (light + .3963377774 * a + .2158037573 * b) ** 3
    m = (light - .1055613458 * a - .0638541728 * b) ** 3
    s = (light - .0894841775 * a - 1.291485548 * b) ** 3
    linear = (4.0767416621*l - 3.3077115913*m + .2309699292*s,
              -1.2684380046*l + 2.6097574011*m - .3413193965*s,
              -.0041960863*l - .7034186147*m + 1.707614701*s)
    return tuple(round(max(0, min(1, 12.92*c if c <= .0031308 else
                 1.055*c**(1/2.4) - .055)) * 255) for c in linear)


def mix(first, second, weight):
    a, b = tokens[first], tokens[second]
    # CSS color-mix(in oklch) uses the shorter hue interpolation by default.
    hue_delta = (b[2] - a[2] + 180) % 360 - 180
    return (a[0]*weight + b[0]*(1-weight), a[1]*weight + b[1]*(1-weight),
            a[2] + hue_delta*(1-weight))


roles = ['challenge-surface', 'challenge-card', 'challenge-text', 'challenge-muted',
         'challenge-border', 'challenge-success', 'challenge-error', 'challenge-info',
         'muted', 'sun', 'milk', 'turquoise', 'coral', 'rust', 'ink']
sectors = ['control', 'observatory', 'shield', 'life', 'greenhouse', 'solar']
values = {key: tokens[key] for key in roles + ['region-' + sector for sector in sectors]}
for sector in sectors:
    key = 'region-' + sector
    values[key + '-badge'] = mix(key, 'challenge-card', .25)
    values[key + '-button'] = mix(key, 'challenge-card', .24)
    values[key + '-border'] = mix(key, 'challenge-border', .40)
    values[key + '-wire'] = mix(key, 'challenge-card', .50)
stylesheet = '/* Generated by Tools/AresImport/export-challenge-colors.py. */\n.ares-root {\n'
for key, value in values.items():
    stylesheet += '    --' + key + ': #' + ''.join(f'{c:02x}' for c in rgb(value)) + ';\n'
stylesheet += '}\n'
(ROOT / 'Assets/ARES/Resources/ARES/UI/ChallengeColors.uss').write_text(stylesheet, encoding='utf-8')

names = {'Ink': 'challenge-text', 'Muted': 'muted', 'Paper': 'challenge-card',
         'Solar': 'region-solar', 'Life': 'region-life', 'Shield': 'region-shield',
         'Green': 'region-greenhouse', 'Observatory': 'region-observatory', 'Control': 'region-control'}
code = '// Generated by Tools/AresImport/export-challenge-colors.py.\nusing UnityEngine;\n\nnamespace Ares.UI\n{\n    internal static class ChallengePalette\n    {\n'
for name, token in names.items():
    code += f'        public static readonly Color {name} = new Color32({", ".join(map(str, rgb(tokens[token])))}, 255);\n'
code += '''        public static Color Sector(string sector)
        {
            switch (sector)
            {
                case "solar": return Solar;
                case "greenhouse": return Green;
                case "lifeSupport": return Life;
                case "shield": return Shield;
                case "observatory": return Observatory;
                default: return Control;
            }
        }
    }
}
'''
(ROOT / 'Assets/ARES/Runtime/UI/ChallengePalette.cs').write_text(code, encoding='utf-8')
print('Exported reference challenge colors to USS and C#.')
